// One-shot generator for lib/face-mesh-topology.ts.
//
// Reads the static connection arrays off MediaPipe's FaceLandmarker and
// flattens each into a plain [a, b, a, b, ...] index list (each pair = one
// line segment between two of the 478 landmarks). The output is committed so
// the *display* bundle never has to import @mediapipe/tasks-vision.
//
//   node scripts/gen-face-topology.mjs
//
// Re-run only if you bump the @mediapipe/tasks-vision version.

import { writeFileSync } from "node:fs";
import { FaceLandmarker } from "@mediapipe/tasks-vision";

const flatten = (conns) => conns.flatMap((c) => [c.start, c.end]);

const TESSELATION_INDEX = flatten(FaceLandmarker.FACE_LANDMARKS_TESSELATION);

// Bright feature lines: face oval + eyes + brows + lips + irises.
const CONTOURS_INDEX = flatten([
  ...FaceLandmarker.FACE_LANDMARKS_FACE_OVAL,
  ...FaceLandmarker.FACE_LANDMARKS_LEFT_EYE,
  ...FaceLandmarker.FACE_LANDMARKS_RIGHT_EYE,
  ...FaceLandmarker.FACE_LANDMARKS_LEFT_EYEBROW,
  ...FaceLandmarker.FACE_LANDMARKS_RIGHT_EYEBROW,
  ...FaceLandmarker.FACE_LANDMARKS_LIPS,
  ...FaceLandmarker.FACE_LANDMARKS_LEFT_IRIS,
  ...FaceLandmarker.FACE_LANDMARKS_RIGHT_IRIS,
]);

const fmt = (arr) => {
  const lines = [];
  for (let i = 0; i < arr.length; i += 30) {
    lines.push("  " + arr.slice(i, i + 30).join(", ") + ",");
  }
  return lines.join("\n");
};

const out = `// AUTO-GENERATED by scripts/gen-face-topology.mjs — do not edit by hand.
//
// Flattened MediaPipe Face Landmarker connection sets as [a, b, a, b, ...]
// index pairs (each pair = one line segment between two of the 478 face
// landmarks). Vendored so the display bundle never imports MediaPipe.

// Full face tessellation net (${TESSELATION_INDEX.length / 2} edges) — rendered dim.
export const TESSELATION_INDEX: number[] = [
${fmt(TESSELATION_INDEX)}
];

// Feature contours: oval + eyes + brows + lips + irises (${CONTOURS_INDEX.length / 2} edges) — rendered bright.
export const CONTOURS_INDEX: number[] = [
${fmt(CONTOURS_INDEX)}
];
`;

const dest = new URL("../lib/face-mesh-topology.ts", import.meta.url);
writeFileSync(dest, out);
console.log(
  `Wrote ${dest.pathname}\n  TESSELATION_INDEX: ${TESSELATION_INDEX.length} ints (${TESSELATION_INDEX.length / 2} edges)\n  CONTOURS_INDEX:    ${CONTOURS_INDEX.length} ints (${CONTOURS_INDEX.length / 2} edges)`,
);
